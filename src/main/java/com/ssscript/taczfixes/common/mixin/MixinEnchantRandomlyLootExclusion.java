package com.ssscript.taczfixes.common.mixin;

import com.ssscript.taczfixes.common.loot.NetheriteBarter;
import net.minecraft.Util;
import net.minecraft.core.Holder;
import net.minecraft.util.RandomSource;
import net.minecraft.world.item.enchantment.Enchantment;
import net.minecraft.world.level.storage.loot.functions.EnchantRandomlyFunction;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Redirect;

import java.util.ArrayList;
import java.util.List;
import java.util.Optional;

/**
 * Keeps this mod's enchantments out of random loot generated by
 * {@code minecraft:enchant_randomly}.
 *
 * <p>When the function has no {@code options}, 1.21.1 rolls over the whole enchantment registry
 * (enchanted books included), so our data-driven enchantments would otherwise leak into chests.
 * This redirect filters them out of the candidate list before the weighted roll happens.</p>
 */
@Mixin(EnchantRandomlyFunction.class)
public abstract class MixinEnchantRandomlyLootExclusion {
    @Redirect(method = "run",
            at = @At(value = "INVOKE",
                    target = "Lnet/minecraft/Util;getRandomSafe(Ljava/util/List;Lnet/minecraft/util/RandomSource;)Ljava/util/Optional;"))
    private static Optional<Holder<Enchantment>> taczfixes$excludeModEnchantmentsFromLoot(
            List<Holder<Enchantment>> candidates, RandomSource random) {
        List<Holder<Enchantment>> filtered = new ArrayList<>(candidates.size());
        for (Holder<Enchantment> holder : candidates) {
            if (!NetheriteBarter.isModEnchantment(holder)) {
                filtered.add(holder);
            }
        }
        return Util.getRandomSafe(filtered, random);
    }
}
