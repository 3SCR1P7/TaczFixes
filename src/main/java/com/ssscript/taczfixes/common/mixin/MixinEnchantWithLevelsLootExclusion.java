package com.ssscript.taczfixes.common.mixin;

import com.ssscript.taczfixes.common.loot.NetheriteBarter;
import net.minecraft.core.Holder;
import net.minecraft.core.HolderSet;
import net.minecraft.core.RegistryAccess;
import net.minecraft.core.registries.Registries;
import net.minecraft.util.RandomSource;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.item.enchantment.Enchantment;
import net.minecraft.world.item.enchantment.EnchantmentHelper;
import net.minecraft.world.level.storage.loot.functions.EnchantWithLevelsFunction;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.injection.At;
import org.spongepowered.asm.mixin.injection.Redirect;

import java.util.Optional;

/**
 * Keeps this mod's enchantments out of random loot generated by
 * {@code minecraft:enchant_with_levels}.
 *
 * <p>{@code EnchantWithLevelsFunction.run} delegates to {@code EnchantmentHelper.enchantItem};
 * with no {@code options} that helper rolls over the entire enchantment registry (books included),
 * so our data-driven enchantments would otherwise leak into chests. This redirect passes a stream
 * without our namespace when no options are configured, and keeps vanilla behavior otherwise.</p>
 */
@Mixin(EnchantWithLevelsFunction.class)
public abstract class MixinEnchantWithLevelsLootExclusion {
    @Redirect(method = "run",
            at = @At(value = "INVOKE",
                    target = "Lnet/minecraft/world/item/enchantment/EnchantmentHelper;enchantItem(Lnet/minecraft/util/RandomSource;Lnet/minecraft/world/item/ItemStack;ILnet/minecraft/core/RegistryAccess;Ljava/util/Optional;)Lnet/minecraft/world/item/ItemStack;"))
    private static ItemStack taczfixes$excludeModEnchantmentsFromLoot(
            RandomSource random, ItemStack stack, int level, RegistryAccess registryAccess,
            Optional<HolderSet<Enchantment>> options) {
        if (options.isPresent()) {
            return EnchantmentHelper.enchantItem(random, stack, level, registryAccess, options);
        }
        return EnchantmentHelper.enchantItem(random, stack, level,
                registryAccess.registryOrThrow(Registries.ENCHANTMENT).holders()
                        .filter(holder -> !NetheriteBarter.isModEnchantment(holder))
                        .map(holder -> (net.minecraft.core.Holder<Enchantment>) holder));
    }
}
